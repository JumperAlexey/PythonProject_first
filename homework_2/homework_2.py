# Задача 10
# Условие: Есть массив чисел. Известно, что каждое число в этом массиве имеет пару,
# кроме одного: `[1, 5, 2, 9, 2, 9, 1]` => `5`. Напишите программу, которая будет выводить уникальное число.
# Решение:
numbers = [1, 5, 2, 9, 2, 9, 1]
counts = {}

for number in numbers:
    counts[number] = counts.get(number, 0) + 1

for number, count in counts.items():
    if count == 1:
# Выводим результат:
        print("Решение задачи 10:")
        print(number)  # 5