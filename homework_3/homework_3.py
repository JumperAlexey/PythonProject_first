# Задача 1. Анализ чисел
# Условие: Напишите программу, которая перебирает все числа от 1 до 30.
# Если число делится на 3, вывести `Bug`, если делится на 5 — `Test`,
# если одновременно на 3 и на 5 — `BugTest`. Во всех остальных случаях — само число.
# Решение:
for number in range(1, 31):
    if number % 3 == 0 and number % 5 == 0:
        print("BugTest")
    elif number % 3 == 0:
        print("Bug")
    elif number % 5 == 0:
        print("Test")
    else:
        print(number)


# Задача 2. Проверка пароля
# Условие: Правильный пароль `Python123` заранее сохранён в программе.
# Пользователю даётся три попытки. При правильном вводе — сообщение об успехе и завершение.
# После трёх неудач — сообщение о блокировке.
#Решение:
correct_password = "Python123"
attempts = 3

for attempt in range(attempts):
    user_password = input("Введите пароль: ")
    if user_password == correct_password:
        print("Авторизация успешна")
        break
else:
    print("Доступ заблокирован")


# Задача 3. Запуск тестов для пользователей
# Условие: Запустить тестирование для пользователей от 1 до 20.
# Пропустить пользователей 5, 10, 15. После пользователя 18 — прервать цикл.
# Решение:
for user_id in range(1, 21):
    if user_id in (5, 10, 15):
        continue
    if user_id == 18:
        break
    print(f"Запуск тестов для пользователя {user_id}")


# Задача 4. Секретное число
# Условие: Секретное число 37. Пользователь вводит числа, пока не угадает.
# После каждой попытки — подсказка «больше/меньше». После успеха — сообщение и количество попыток.
# Решение:
secret = 37
attempts = 0

while True:
    guess = int(input("Введите число: "))
    attempts += 1
    if guess < secret:
        print("Загаданное число больше")
    elif guess > secret:
        print("Загаданное число меньше")
    else:
        print(f"Угадали! Количество попыток: {attempts}")
        break

# Задача 5. Результаты автотестов
# Условие: Пользователь вводит количество тестов, затем статус каждого: `PASS`, `FAIL`, `SKIP`. Программа подсчитывает статистику. Если есть хотя бы один `FAIL` — сообщить о падениях, иначе — об успехе. Неизвестные статусы игнорировать.
# Решение:
total = int(input("Введите количество тестов: "))
passed = 0
failed = 0
skipped = 0

for _ in range(total):
    status = input("Введите статус теста (PASS/FAIL/SKIP): ").strip().upper()
    if status == "PASS":
        passed += 1
    elif status == "FAIL":
        failed += 1
    elif status == "SKIP":
        skipped += 1
    # неизвестные статусы игнорируем

print(f"PASS: {passed}")
print(f"FAIL: {failed}")
print(f"SKIP: {skipped}")

if failed > 0:
    print("Есть упавшие тесты")
else:
    print("Все тесты прошли успешно")