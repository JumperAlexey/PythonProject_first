# Задание 4
# Условие: В строке `"Ivanou Ivan"` поменяйте слова местами
# Решение:
text = "Ivanou Ivan"
# Разбиваем строку на список слов
words = text.split()
# Меняем слова местами
result = words[1] + " " + words[0]
# Выводим результат:
print("Решение задачи 4")
print(result)


# Задание 5
# Условие: Напишите программу, которая удаляет пробелы в начале и конце строки.
# Решение:
text = "    Привет, мир!    "
# Метод strip() удаляет пробелы слева и справа
result = text.strip()
# Выводим результат:
print("Решение задачи 5")
print(result)