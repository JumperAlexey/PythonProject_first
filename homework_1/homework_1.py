# Задача 1
# Условие: Привести к целому типу числа `-1.6` и `2.99`.
# Решение:
a = -1.6
b = 2.99
# Функция int() отбрасывает дробную часть
a_int = int(a)
b_int = int(b)
# Выводим результат:
print("Решение задачи 1:")
print(a_int)
print(b_int)


# Задание 2
# Условие: Заменить символ `#` на символ `/` в строке: www.my_site.com#about
# Решение:
url = "www.my_site.com#about"
# Метод replace() заменяет один символ на другой
new_url = url.replace("#", "/")
# Выводим результат:
print("Решение задачи 2")
print(new_url)


